  var LANG = "en";

  function pack() {
    return LANG === "pt" ? PT : EN;
  }

  function t(key, vars) {
    var dict = pack();
    var s = dict[key];
    if (s == null) s = EN[key];
    if (s == null) return key;
    if (vars) {
      s = String(s).replace(/\{(\w+)\}/g, function (_, k) {
        return vars[k] == null ? "" : String(vars[k]);
      });
    }
    return s;
  }

  function locale() {
    return LANG === "pt" ? "pt-BR" : "en-US";
  }

  function nth(n) {
    n = Number(n) || 0;
    if (LANG === "pt") return n + "º";
    var v = n % 100;
    var s = ["th", "st", "nd", "rd"];
    return n + (s[(v - 20) % 10] || s[v] || s[0]);
  }

  function unitOf(ch) {
    if (!ch) return "";
    var uk = ch.uk || UNIT_BY_CH[ch.k];
    return uk ? t("unit." + uk) : (ch.u || "");
  }

  function src(label) {
    var k = SRC_KEY[String(label || "").toLowerCase()];
    return k ? t(k) : label;
  }

  function status(raw) {
    var k = ST_KEY[String(raw || "done").toLowerCase()];
    return k ? t(k) : raw;
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      if (!k) return;
      var attr = el.getAttribute("data-i18n-attr");
      var vars = {};
      var n = el.getAttribute("data-i18n-n");
      if (n) vars.n = n;
      var val = t(k, vars);
      if (attr) el.setAttribute(attr, val);
      else el.textContent = val;
    });
    root.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var k = el.getAttribute("data-i18n-html");
      if (k) el.innerHTML = t(k);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var k = el.getAttribute("data-i18n-placeholder");
      if (k) el.setAttribute("placeholder", t(k));
    });
    root.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      var k = el.getAttribute("data-i18n-title");
      if (k) el.setAttribute("title", t(k));
    });
  }

  function syncButtons() {
    document.querySelectorAll("[data-lang-set]").forEach(function (b) {
      b.setAttribute("aria-pressed", b.getAttribute("data-lang-set") === LANG ? "true" : "false");
    });
  }

  function boot(lang) {
    LANG = lang === "pt" ? "pt" : "en";
    document.documentElement.setAttribute("data-lang", LANG);
    document.documentElement.setAttribute("lang", LANG === "pt" ? "pt-BR" : "en-US");
    apply(document);
    syncButtons();
  }

  function set(lang) {
    lang = lang === "pt" ? "pt" : "en";
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    boot(lang);
    try { document.dispatchEvent(new CustomEvent("spy-lang", { detail: { lang: lang } })); } catch (e) {}
  }

  function get() {
    try {
      var s = localStorage.getItem(KEY);
      return s === "pt" ? "pt" : "en";
    } catch (e) {
      return "en";
    }
  }

  document.addEventListener("click", function (e) {
    var b = e.target.closest && e.target.closest("[data-lang-set]");
    if (!b) return;
    e.preventDefault();
    set(b.getAttribute("data-lang-set"));
  });

  LANG = get();
  document.documentElement.setAttribute("data-lang", LANG);
  document.documentElement.setAttribute("lang", LANG === "pt" ? "pt-BR" : "en-US");

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () {
      apply(document);
      syncButtons();
    });
  } else {
    apply(document);
    syncButtons();
  }

